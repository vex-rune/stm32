/**
 * @brief  写 16-bit 数据到 LCD (用于设置窗口坐标/GRAM 像素等)
 * @param  data  16-bit 数据
 * @note   ILI9486 大多数数据操作使用 16-bit 接口 (RGB565, 坐标值)
 */
static void lcd_write_data(uint16_t data)
{
    LCD_RAM = data;
}

/**
 * @brief  写 8-bit 数据到 LCD (用于初始化序列中部分 8-bit 参数寄存器)
 * @param  data  8-bit 数据
 * @note   当 R0x3A = 0x55 (DPI=101) 时, 数据总线低 8 位有效,
 *         控制器仅读取 DBI[7:0]。本项目 16-bit 总线直接写低 8 位即可。
 */
static void lcd_write_data8(uint8_t data)
{
    LCD_RAM = (uint16_t)data;
}

/** 读取
 */
static uint16_t lcd_read_data(void)
{
    return LCD_RAM;
}

/*============================================================================
 * ILI9486 初始化序列 (适配 Z350IT002 320x480 模块)
 *============================================================================*/

/**
 * @brief  ILI9486 复位 + 寄存器配置
 */
static void lcd_init_sequence(void)
{
    /* 1) 硬件复位 */
    LCD_RST_CLR();
    HAL_Delay(20);
    LCD_RST_SET();
    HAL_Delay(20);
    LCD_BL_SET();
    HAL_Delay(20);

    /* 2) 软件复位 + Sleep Out */
    lcd_write_reg(0x01);
    HAL_Delay(120);
    lcd_write_reg(0x11);
    HAL_Delay(120);

    /* 3) 像素格式: 16-bit RGB565 */
    lcd_write_reg(0x3A);
    lcd_write_data8(0x55);

    /* 4) 电源控制 */
    lcd_write_reg(0xC0);
    lcd_write_data8(0x10);
    lcd_write_data8(0x10);
    lcd_write_reg(0xC1);
    lcd_write_data8(0x41);
    lcd_write_reg(0xC5);
    lcd_write_data8(0x00);
    lcd_write_data8(0x22);
    lcd_write_data8(0x80);

    /* 5) 显示方向: BGR=1 */
    lcd_write_reg(0x36);
    lcd_write_data8(0x08);

    /* 6) 显示功能 */
    lcd_write_reg(0xB6);
    lcd_write_data8(0x02);
    lcd_write_data8(0x02);
    lcd_write_data8(0x3B);
    lcd_write_reg(0xB7);
    lcd_write_data8(0xC6);
    lcd_write_reg(0xBE);
    lcd_write_data8(0x00);
    lcd_write_data8(0x04);
    lcd_write_reg(0xB4);
    lcd_write_data8(0x02);

    /* 7) 帧率 70Hz */
    lcd_write_reg(0xB1);
    lcd_write_data8(0xB0);
    lcd_write_data8(0x11);

    /* 8) RGB 接口关闭 (使用 MCU 接口) */
    lcd_write_reg(0xB3);
    lcd_write_data8(0x02);
    lcd_write_data8(0x00);
    lcd_write_data8(0x00);
    lcd_write_data8(0x00);

    /* 9) Gamma 校正 */
    lcd_write_reg(0xF2);
    lcd_write_data8(0x00);
    lcd_write_reg(0x26);
    lcd_write_data8(0x01);

    /* R0xE0: Positive Gamma */
    lcd_write_reg(0xE0);
    lcd_write_data8(0x0F);
    lcd_write_data8(0x1E);
    lcd_write_data8(0x1C);
    lcd_write_data8(0x0A);
    lcd_write_data8(0x0F);
    lcd_write_data8(0x08);
    lcd_write_data8(0x47);
    lcd_write_data8(0xB3);
    lcd_write_data8(0x3B);
    lcd_write_data8(0x0A);
    lcd_write_data8(0x14);
    lcd_write_data8(0x06);
    lcd_write_data8(0x0E);
    lcd_write_data8(0x09);
    lcd_write_data8(0x00);

    /* R0xE1: Negative Gamma */
    lcd_write_reg(0xE1);
    lcd_write_data8(0x0F);
    lcd_write_data8(0x36);
    lcd_write_data8(0x2F);
    lcd_write_data8(0x0A);
    lcd_write_data8(0x0F);
    lcd_write_data8(0x06);
    lcd_write_data8(0x47);
    lcd_write_data8(0xB3);
    lcd_write_data8(0x3A);
    lcd_write_data8(0x0A);
    lcd_write_data8(0x14);
    lcd_write_data8(0x06);
    lcd_write_data8(0x0E);
    lcd_write_data8(0x09);
    lcd_write_data8(0x00);

    /* 10) Display ON */
    lcd_write_reg(0x29);
    HAL_Delay(50);
}


