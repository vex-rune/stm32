/**
  ******************************************************************************
  * @file    lcd.c
  * @brief   LCD 驱动实现 (FSMC 8080 接口, ILI9486 控制器, Z350IT002 320x480)
  *
  * @note
  *   本文件实现 lcd.h 中声明的所有 API。依赖 STM32 HAL 库提供的 FSMC
  *   总线读写, 寄存器时序由 MX_FSMC_Init() 配置。
  *
  *   数据宽度: 16-bit (RGB565)
  *   命令/数据切换: 通过 FSMC 地址线 A10 (PG0) 实现
  *     - LCD_REG (0x6C000000) -> A10=0 -> 写命令
  *     - LCD_RAM (0x6C000800) -> A10=1 -> 写数据
  *
  *   接线:
  *     FSMC_D0  ~ FSMC_D15  -> 数据线
  *     FSMC_NE4 -> PG12     -> LCD CS
  *     FSMC_NOE -> PD4      -> LCD RD
  *     FSMC_NWE -> PD5      -> LCD WR
  *     FSMC_A10 -> PG0      -> LCD RS (命令/数据)
  *     PB0      -> LCD BL   -> 背光
  *     PG15     -> LCD RST  -> 复位
  *
  *   调用顺序 (main.c 中):
  *     1. HAL_Init();
  *     2. SystemClock_Config();
  *     3. MX_GPIO_Init();    // 初始化 PB0 / PG15
  *     4. MX_FSMC_Init();    // 初始化 FSMC 总线
  *     5. LCD_Init();        // 本文件提供的初始化
  *     6. LCD_Clear(WHITE);  // 清屏
  *     7. LCD_ShowString(...)// 显示内容
  ******************************************************************************
  */
