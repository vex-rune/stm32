/**
 * @brief  LCD 总初始化
 *
 * 执行步骤:
 *   1. 填写 lcddev 结构体 (Z350IT002 -> ILI9486, 320x480, 竖屏)
 *   2. 硬件复位 + ILI9486 寄存器初始化序列
 *   3. 设置显示方向
 *   4. 点亮背光
 *   5. 清屏 (白色)
 *
 * @note   调用前必须先完成 MX_GPIO_Init() 和 MX_FSMC_Init()
 * @warning 本函数包含不短延 ( ~ 200ms), 必要时可以在初始化阶段调用
 */
void LCD_Init(void)
{
    // 基础信息
    lcddev.id = 0x9486; /* Z350IT002 -> ILI9486 控制器 */
    lcddev.width = 320; /* 默认竖屏 320 x 480 */
    lcddev.height = 480;
    lcddev.dir = LCD_DIR_VERTICAL;


    /* 复位 : 先拉低, 在拉高*/
    LCD_RST_CLR();
    LCD_RST_SET();

    /* 打开背光 */
    LCD_BL_SET();

    /* 初始化序列 */
    lcd_init_sequence();

    // 初始化寄存器的值
    LCD_DisplayDir(lcddev.dir); /* 根据方向更新 lcddev.width/height */
    LCD_Clear(WHITE); /* 清屏 */
}

// 测试屏幕方向
void LCD_TestDir(void)
{
    LCD_Write_Font('1', 1, 0, 0, RED); // (0, 0)
    LCD_Write_Font('2', 1, lcddev.width - 8, 0, RED); // 期望右上 (代码语义)
    LCD_Write_Font('3', 1, 0, lcddev.height - 16, RED); // 期望左下
    LCD_Write_Font('4', 1, lcddev.width - 8, lcddev.height - 16, RED); // 期望右下
    LCD_Write_Font('5', 1, lcddev.width / 2 - 4, lcddev.height / 2 - 8, RED); // 期望中心
}


/**
 * @brief  打开 LCD 显示 (等同于 R0x29: Display ON)
 */
void LCD_DisplayOn(void)
{
    lcd_write_reg(0x29);
}

/**
 * @brief  关闭 LCD 显示 (等同于 R0x28: Display OFF)
 * @note   进入 Display OFF 后控制逻辑仍在运行, 仅不输出图像
 */
void LCD_DisplayOff(void)
{
    lcd_write_reg(0x28);
}


/**
 * @brief  设置 GRAM 绘图窗口
 * @param  xstar,ystar  窗口左上角
 * @param  xend,yend    窗口右下角
 * @note   设置窗口后, 后续 LCD_RAM 写入将自动按窗口顺序填充,
 *         适合批量绘制 (例如填充矩形, 显示大字符)。使用完窗口后
 *         建议调用 LCD_SetWindow(0, 0, width-1, height-1) 恢复全屏。
 */
void LCD_SetWindow(uint16_t xstar, uint16_t ystar, uint16_t w, uint16_t h)
{
    // 设置窗口
    // 列地址
    lcd_write_reg(0x2a);

    // 开始列
    lcd_write_data(xstar >> 8);
    lcd_write_data(xstar & 0xFF);

    // 计算结束列
    uint16_t xend = xstar + w - 1;
    // 结束列
    lcd_write_data(xend >> 8);
    lcd_write_data(xend & 0xFF);

    // 行地址
    lcd_write_reg(0x2b);

    // 开始行
    lcd_write_data(ystar >> 8);
    lcd_write_data(ystar & 0xFF);

    // 计算结束行
    uint16_t yend = ystar + h - 1;
    // 结束行
    lcd_write_data(yend >> 8);
    lcd_write_data(yend & 0xFF);
}


/**
 * @brief  全屏填充单一颜色
 * @param  color  RGB565 颜色
 *
 * 实现要点:
 *   - 调用 LCD_SetWindow 设置全屏窗口
 *   - 发送 R0x2C (Write GRAM) 命令
 *   - 连续写入 width*height 个颜色值
 *
 * @warning 总写入量 = width * height, 在 320x240 屏为 76800 次。
 *          通过 FSMC 直接写寄存器, 速度极快, 不需要使用 DMA。
 */
void LCD_Clear(uint16_t color)
{
    // 设置全屏
    LCD_SetWindow(0, 0, lcddev.width - 1, lcddev.height - 1);

    // 发送 GRAM 命令
    lcd_write_reg(0x2c);

    // 设置所有像素点, 注意 lcddev.width * lcddev.height 的大小, 所以用 uint32_t
    for (uint32_t i = 0; i < lcddev.width * lcddev.height; i++)
    {
        lcd_write_data(color);
    }
}


/**
 * @brief  设置 LCD 扫描方向 (ILI9341 R0x36 MADCTL)
 * @param  dir  0~7 对应 8 种扫描方式
 *
 * R0x36 位域含义 (bit7~bit5):
 *   MY (bit7) - 行地址顺序
 *   MX (bit6) - 列地址顺序
 *   MV (bit5) - 行/列交换
 *   ML (bit4) - 垂直刷新顺序
 *   BGR (bit3) - RGB->BGR 顺序
 *   MH (bit2) - 水平刷新顺序
 *
 * 常用组合:
 *   0 -> 竖屏 RGB
 *   5 -> 横屏 RGB
 *   6 -> 竖屏 RGB 反向
 *   3 -> 横屏 RGB 反向
 */
void LCD_ScanDir(uint8_t dir)
{
    uint16_t regval = 0;
    switch (dir)
    {
    case 0: regval = (0 << 7) | (0 << 6) | (0 << 5);
        break; /* MY=0,MX=0,MV=0 */
    case 1: regval = (0 << 7) | (1 << 6) | (0 << 5);
        break; /* MY=0,MX=1,MV=0 */
    case 2: regval = (1 << 7) | (0 << 6) | (1 << 5);
        break; /* MY=1,MX=0,MV=1 */
    case 3: regval = (1 << 7) | (1 << 6) | (1 << 5);
        break; /* MY=1,MX=1,MV=1 */
    case 4: regval = (0 << 7) | (0 << 6) | (1 << 5);
        break; /* MY=0,MX=0,MV=1 */
    case 5: regval = (0 << 7) | (1 << 6) | (1 << 5);
        break; /* MY=0,MX=1,MV=1 */
    case 6: regval = (1 << 7) | (0 << 6) | (0 << 5);
        break; /* MY=1,MX=0,MV=0 */
    case 7: regval = (1 << 7) | (1 << 6) | (0 << 5);
        break; /* MY=1,MX=1,MV=0 */
    }
    regval |= 0x08; /* 强制 BGR=1 (ILI9341 默认数据顺序为 BGR) */
    lcd_write_reg(0x36);
    lcd_write_data8(regval);
}

/**
 * @brief  设置显示方向, 同时同步更新 lcddev.width/height
 * @param  dir  LCD_DIR_HORIZONTAL(横屏 320x240) / LCD_DIR_VERTICAL(竖屏 240x320)
 * @note   调用后, 之前设置的窗口/光标已失效, 需重新调用 LCD_SetWindow
 */
void LCD_DisplayDir(uint8_t dir)
{
    if (dir == LCD_DIR_HORIZONTAL)
    {
        lcddev.width = 480; /* 横屏: 宽 480, 高 320 */
        lcddev.height = 320;
        LCD_ScanDir(5); /* 横屏: MY=0,MX=1,MV=1,BGR=1 */
    }
    else
    {
        lcddev.width = 320; /* 竖屏: 宽 320, 高 480 (Z350IT002 物理方向) */
        lcddev.height = 480;
        LCD_ScanDir(1); /* 竖屏: MY=0,MX=0,MV=0,BGR=1 */
    }
    lcddev.dir = dir;
}

/**
 * 读取 id
 *
 * 是个3字节的数据类型
 */
uint32_t LCD_ReadID(void)
{
    lcd_write_reg(0x04);

    // 每次只能读 1 个字节, 一共是 3 个字节
    uint32_t id = 0;

    id |= (lcd_read_data() & 0xFF) << 24;
    id |= (lcd_read_data() & 0xFF) << 16;
    id |= (lcd_read_data() & 0xFF) << 8;
    id |= (lcd_read_data() & 0xFF);

    return id;
}

void do_row(int size, int w, uint16_t color, uint8_t row)
{
    for (int j = 0; j < w; j++)
    {
        int f = row & 0x80;
        // 获取当前像素点
        if (f)
        {
            for (int k = 0; k < size; k++)
            {
                lcd_write_data(color);
            }
        }
        else
        {
            for (int k = 0; k < size; k++)
            {
                lcd_write_data(WHITE);
            }
        }
        row <<= 1;
    }
}

// 8x16
void LCD_Write_Font(char str, int size, uint16_t x, uint16_t y, uint16_t color)
{
    // 1. 范围保护: 仅支持 0x20 ~ 0x7F
    unsigned char c = (unsigned char)str;
    if (c < 0x20 || c > 0x7F)
    {
        return;
    }

    int f_w = 8;
    int f_h = 16;
    int w = 8 * size;
    int h = 16 * size;


    // 2. 确定区域 (16 行 x 8 列)
    LCD_SetWindow(x, y, w, h);

    // 3. 发送写 GRAM 指令
    lcd_write_reg(0x2c);

    // 4. 计算字符起始字节偏移: ' ' 对应 0, 'A' 对应 (0x41-0x20)*16 = 528
    int begin_index = (c - 0x20) * f_h;

    // 遍历每一行
    for (int i = 0; i < f_h; i++)
    {
        uint8_t row = ascii_8x16[begin_index + i];

        for (int i = 0; i < size; ++i)
        {
            do_row(size, f_w, color, row);
        }
    }
}

void LCD_Write_Fonts(char* str, int size, int len, uint16_t x, uint16_t y, uint16_t color)
{
    for (int i = 0; i < len; i++)
    {
        LCD_Write_Font(str[i], size, (x + i * 8) * size, y, color);
    }
}

void LCD_Write_C(const uint8_t font_c[], int size, uint16_t x, uint16_t y, uint16_t color)
{
    // 0) 边界检查
    if (font_c == 0 || size <= 0)
    {
        return;
    }
    if (x + 16 * size > lcddev.width || y + 16 * size > lcddev.height)
    {
        return;
    }

    // 1) 字模尺寸: 高 16 行, 宽 16 位 (每行 2 字节)
    //    注意: do_row 内部仅按 uint8_t (8 位) 处理, 所以下面传 w=8, 调用 2 次
    const int f_w_byte = 8;          // 每个字节 = 8 列
    const int f_h = 16;              // 16 行
    const int w = 16 * size;         // 总像素宽
    const int h = 16 * size;         // 总像素高

    // 2) 设置窗口 (16 行 x 16 列, 按 size 放大)
    LCD_SetWindow(x, y, w, h);

    // 3) 发送写 GRAM 指令
    lcd_write_reg(0x2c);

    // 4) 遍历每一行: 每行读 2 字节 (左半行 + 右半行)
    for (int row_idx = 0; row_idx < f_h; row_idx++)
    {
        uint8_t row_left  = font_c[row_idx * 2];      // 高字节 (左半行, MSB 在左)
        uint8_t row_right = font_c[row_idx * 2 + 1];  // 低字节 (右半行)

        // 5) 沿垂直方向放大 size 倍
        for (int s = 0; s < size; s++)
        {
            do_row(size, f_w_byte, color, row_left);   // 前 8 列
            do_row(size, f_w_byte, color, row_right);  // 后 8 列
        }
    }
}
